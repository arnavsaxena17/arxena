const linkedinDraftPrompt = (
  findId: string,
  profileId: string,
  kind: 'opener' | 'fu1' | 'fu2' | 'fu3',
) => {
  const intro = {
    opener:
      'Draft a short first LinkedIn message after the connection was accepted.\nPrioritise rapport. Meeting is a light close, not a calendar dump.',
    fu1: 'Draft LinkedIn follow-up 1 of 3. Escalate value, do not pressure.',
    fu2: 'Draft LinkedIn follow-up 2 of 3. Escalate value, do not pressure.',
    fu3: 'Draft LinkedIn follow-up 3 of 3. This is the breakup note if they are silent.',
  }[kind];

  return [
    intro,
    `Name: ${gtmWfFindField(findId, 'name')}`,
    `Title: ${gtmWfFindField(findId, 'jobTitle')}`,
    `About: {{${profileId}.about}}`,
    `Skills: {{${profileId}.skills}}`,
    'Return JSON only: { "message": "<body>" }',
  ].join('\n');
};

const followUpSteps = ({
  n,
  findId,
  filterId,
  draftId,
  approveId,
  sendId,
  stampId,
  waitId,
  nextFindId,
  isLast,
}: {
  n: 1 | 2 | 3;
  findId: string;
  filterId: string;
  draftId: string;
  approveId: string;
  sendId: string;
  stampId: string;
  waitId?: string;
  nextFindId?: string;
  isLast: boolean;
}) => [
  candidateFind(findId, `Reload candidate before follow-up ${n}`, [filterId]),
  gtmWfFilterStep({
    id: filterId,
    name: `No reply yet (follow-up ${n})`,
    stepOutputKey: gtmWfFindField(findId, 'outreachSequenceStage'),
    value: 'CONNECTION_ACCEPTED',
    nextStepIds: [draftId],
  }),
  gtmWfAiAgentStep({
    id: draftId,
    name: `Draft LinkedIn follow-up ${n}`,
    prompt: linkedinDraftPrompt(
      findId,
      IDS.fetchProfile,
      `fu${n}` as 'fu1' | 'fu2' | 'fu3',
    ),
    agentId: OUTREACH_WF_AGENT_LINKEDIN,
    outputSchema: OUTREACH_WF_AI_MESSAGE_OUTPUT,
    nextStepIds: [approveId],
  }),
  gtmWfFormStep({
    id: approveId,
    name: `Approve follow-up ${n}`,
    editedBodyValue: `{{${draftId}.message}}`,
    contextTemplate: `Review LinkedIn follow-up ${n}`,
    detailsTemplate: gtmWfFormDetailsTemplate({
      findId,
      draftStepId: draftId,
    }),
    nextStepIds: [sendId],
  }),
  gtmWfSendLinkedInMessageStep({
    id: sendId,
    name: `Send follow-up ${n}`,
    body: `{{${approveId}.editedBody}}`,
    candidateId: gtmWfFindId(findId),
    linkedinProfileId: gtmWfFindField(findId, 'linkedinProfileId'),
    nextStepIds: [stampId],
  }),
  gtmWfUpdateRecordStep({
    id: stampId,
    name: `Stamp follow-up ${n}`,
    objectRecordId: gtmWfFindId(findId),
    objectRecord: isLast
      ? {
          linkedinFollowUpCount: n,
          outreachSequenceStage: 'FAILED_NO_REPLY',
        }
      : { linkedinFollowUpCount: n },
    nextStepIds: waitId ? [waitId] : undefined,
  }),
  ...(waitId && nextFindId
    ? [
        gtmWfDelayStep({
          id: waitId,
          name: `Wait before follow-up ${n + 1}`,
          days: 3,
          nextStepIds: [nextFindId],
        }),
      ]
    : []),
];

