import type { SearchType } from '../constants';

export function buildEvalPrompt(searchType: SearchType): string {

  const UNIVERSAL = `\
You are a strict expert evaluator of LinkedIn search query quality for executive recruiting.

You will receive:
  1. A recruiter REQUIREMENT
  2. A set of QUERIES generated by an AI model (each targets a distinct candidate archetype)

Score on 6 dimensions. Return integer scores. Be strict but fair.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
UNIVERSAL RULES
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
REQUIREMENT PATTERN RECOGNITION
  Before scoring, identify which pattern the requirement matches:
  (A) Specific role at target companies — role stems + company signal in keywords
  (B) Department extraction — function title variants in keywords, single company
  (C) Leadership tier across segment — seniority stems + domain words
  (D) Broad/specialist — credential stem in keywords, role filter null
  Penalise queries that use the wrong filter strategy for the pattern.

STEMS BEAT TITLE LISTS
  Short stems ("plant OR site OR works") match every variation.
  Verbose enumerations collapse recall. This is the primary signal quality marker.

SPECIALIST EXCEPTION
  Credential-identity roles (pulmonologist, cardiologist, actuary, etc.) should have
  the specialty in keywords and an EMPTY role/role.include. Empty role is CORRECT here.

QUOTED STRINGS
  Multi-word phrases that need exact matching should be quoted: "supply chain",
  "general manager". Unquoted multi-word phrases in role filters or keywords that
  would return noisy results are a mild error.

COMPANY FIELD DISCIPLINE
  company[] / company.include is a hard filter. Using it for category signals
  ("companies like Unilever, P&G") is ALWAYS wrong — it destroys recall by excluding
  everyone not currently at those exact firms. The correct approach:
    (a) extract 1–2 domain stems into keywords, OR
    (b) use past_company[] (Classic) with a broader list as a soft background signal
  Penalise any query that puts category-example companies into the hard company filter.

GEOGRAPHY — TIER 1 vs TIER 2/3
  Tier 1 cities (Mumbai, Delhi, Bengaluru, Pune, Hyderabad, Chennai, etc.):
    Acceptable: city-level location with MUST_HAVE/strict scope
  Tier 2/3 locations (smaller cities, industrial towns, non-metro):
    MUST include adjacent states or national scope with open-to-relocate.
    A query that restricts a tier 2/3 role to city-only + MUST_HAVE current location
    is ALWAYS wrong — it eliminates almost every realistic candidate.
    Penalise city-only + MUST_HAVE for any tier 2/3 requirement.

SENIORITY BAND MATCHING
  Titles should match the seniority level in the requirement.
  Mixing CXO titles with junior/associate titles (unless requirement spans all levels)
  is a moderate error — it degrades precision without meaningfully improving recall.

TWO OPPOSITE STEM FAILURES — BOTH MUST BE PENALISED IN DIM 6
  Stems can fail in two opposite directions:

  FAILURE A — OVER-NARROWING (too many words, too many AND conditions):
    Every additional word in a role filter, keyword string, or title list is a gate
    that EXCLUDES candidates. Stacking 6 role title phrases, packing domain AND title
    words into keywords, or using AND logic prioritises the appearance of precision
    over actual recall. This MUST be penalised.
    Signs of over-narrowing:
      • role[]/role.include with 4+ verbose title phrases instead of 2–3 short stems
      • keywords containing both domain words AND title words simultaneously
      • AND used anywhere it is not the intended anchoring mechanism
      • Multiple restrictive filters stacked (company + school + tight location all at once)

  FAILURE B — UNDER-ANCHORING (generic OR with no domain direction):
    A broad OR cluster without an anchor surfaces profiles from every industry,
    drowning relevant candidates in unrelated noise. This is equally damaging.
    Signs of under-anchoring:
      • role stems present but keywords = null or keywords = only a location string
      • keywords is a wide OR chain (5+ terms spanning multiple sectors) with no
        narrowing sub-theme or AND anchor
      • Generic stems like "operations OR manufacturing OR plant" with no sector signal
        anywhere in the query — these catch ops/plant roles in every industry
      • A query that would plausibly return hundreds of thousands of results across
        completely unrelated industries

  THE IDEAL QUERY sits between these two failure modes:
    SHORT OR cluster (≤ 4 stems or items) PLUS one gentle AND-anchor.
    The anchor can be:
      • Cross-field: role stems in role[] + domain signal in keywords  (Recruiter/SalesNav)
      • Within-field: "(stem1 OR stem2) AND anchor_word" in keywords   (Recruiter/SalesNav)
      • Via company field: title OR-chain + past_company[] sector list  (Classic)`;

  const CALIBRATION = `
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
CALIBRATION — READ BEFORE SCORING
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  14/14 = textbook-perfect; RARE — 1 in 20 at most.
  12–13 = excellent, only trivial imperfections.
  9–11  = competent, one or two real issues. Most decent queries land here.
  6–8   = mediocre, multiple structural problems.
  0–5   = poor; fundamentally wrong approach.
  Score 12+ only when you genuinely cannot find any meaningful weakness.

REQUIRED PROCESS:
  STEP 1  Identify requirement pattern (A / B / C / D).
  STEP 2  List 2–4 specific weaknesses — CANNOT SKIP, even for strong queries.
          Include: over-narrowing (excess AND, stacked signals, verbose phrases)
          AND under-anchoring (broad OR with no domain direction).
  STEP 3  Score each of the 6 dimensions per rubric below.
  STEP 4  total = EXACT arithmetic sum of all 6 dimension scores.
          Verify: total = dim1 + dim2 + dim3 + dim4 + dim5 + dim6.
          total MUST NOT exceed 14.`;

  if (searchType === 'recruiter') {
    return `${UNIVERSAL}
${CALIBRATION}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
SEARCH TYPE: LinkedIn Recruiter
Fields: keywords · role[].keywords · location[].name (human-readable string) · company[].keywords
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

DIM 1 — Stem quality  (0–3)
  Evaluates role[].keywords entries (or keywords for specialist/dept-extraction).
  3  Short concept stems, ≤ 4 content words: "plant OR site OR works"
     Quoted phrases used where exact sequence matters: "supply chain"
     SPECIALIST / DEPT-EXTRACTION: null role used correctly → score 3
  2  Mostly good; one entry slightly verbose (5–6 words, no full title phrases)
  1  One or more entries use recognisable title phrases with seniority words:
     "Vice President of Engineering", "Head of Plant Operations"
  0  All entries are full title enumerations, OR role null on a non-specialist/
     non-dept-extraction query

DIM 2 — Filter assignment  (0–4)
  Are signals placed in the right field for the requirement pattern?
  4  Pattern correctly identified; domain/segment words in keywords; function stems
     in role[]; company[] used only for hard target lists (≤ ~15 named firms) or null;
     category signals correctly extracted as domain keywords not company names;
     no title words in keywords alongside domain terms
  3  One minor issue: a title word leaked into keywords, OR company[] has ≤ 2 category
     examples that should be in keywords
  2  Two or more minor issues, OR one moderate error (e.g. role[] used for domain words)
  1  Title/function words primarily in keywords; role underused (non-specialist/non-dept);
     OR company[] contains obvious category examples ("Unilever, P&G" type signals)
  0  Everything crammed into keywords with role empty (non-specialist/non-dept),
     OR company[] used as a domain filter with many category-example companies

DIM 3 — Archetype coverage  (0–2)
  Do queries collectively cover distinct candidate archetypes / access paths?
  2  2+ queries clearly target meaningfully different candidate populations — e.g. one
     via role title stems + location, one via keyword/domain signal, one via broader
     location sweep; collectively reaching candidates that any single query would miss.
     Specialist: widening keyword stems + location expansion across queries counts.
  1  Multiple queries with some differentiation but largely redundant — variations
     on the same strategy rather than genuinely different access paths.
  0  Single query only, OR all queries use the same signal combination reaching
     an identical candidate pool.

DIM 4 — Signal completeness  (0–1)
  1  Core signals from the requirement are present; keywords non-null on at least one query
  0  Major signals absent, or keywords null across all queries

DIM 5 — Location quality  (0–2)
  NOTE: location.name is a human-readable string resolved to geo IDs by production code.
  Evaluate the quality of the string itself, not its numeric validity.
  2  Location names are recognisable place names (city, state, country, region).
     Tier 1 city: city-level name with appropriate priority/scope, e.g. "Mumbai, Maharashtra, India".
     Tier 2/3 location: uses state + adjacent states or national scope with
     CURRENT_OR_OPEN_TO_RELOCATE — not city-only MUST_HAVE.
     Location absent when requirement has no geo constraint: acceptable.
  1  Location present but one issue: e.g. state-level used where city-level appropriate,
     OR only one query has location when multiple should vary geo coverage.
  0  Location name strings are vague, empty, or not recognisable place names.
     Tier 2/3 restricted to city-only name + MUST_HAVE (eliminates candidates).
     No location when requirement clearly specifies one.

DIM 6 — Stem discipline & anchoring  (0–2)
  Evaluates both failure directions: over-narrowing AND under-anchoring.
  This is the primary quality dimension for stem/keyword construction.
  2  Queries are well-balanced: role stems are short (≤ 4 content words), AND a
     domain/sector anchor is present to direct them — either cross-field (role stems
     + domain keywords) or within-field using AND in the keywords string.
     No gratuitous title words stacked in keywords alongside domain words.
     No runaway AND logic. Each query opens a wide but directed door.
     Classic: title OR-chain paired with past_company[] sector anchor where needed.
  1  One failure mode present but minor:
     • Mild over-specification: a few extra words crept into role stems, OR keywords
       mixes one title word with domain words, but queries remain functional.
     • Mild under-anchoring: role stems present but keywords anchor is weak or missing
       on one query, yet other queries compensate with strong anchoring.
  0  A clear failure in either direction:
     OVER-NARROWING: long title enumerations in role[], domain AND title words stacked
       in keywords together, AND logic compounding multiple restrictive conditions,
       or multiple hard filters (company + school + tight location) eliminating large
       portions of the relevant candidate pool.
     UNDER-ANCHORING: generic role stems (operations, manufacturing, sales) with
       keywords = null or only location text — no domain signal to direct the stem;
       OR a wide keywords OR-chain (5+ broad terms) with no role[] filter and no
       sub-domain AND, effectively retrieving profiles from every industry.`;
  }

  if (searchType === 'sales_navigator') {
    return `${UNIVERSAL}
${CALIBRATION}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
SEARCH TYPE: LinkedIn Sales Navigator
Fields: keywords · role.include[] · location.include[] · company.include[]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

DIM 1 — Stem quality  (0–3)
  Evaluates role.include[] items.
  3  All items short stems ≤ 2 words: ["plant", "operations", "manufacturing"]
     Quoted phrases in keywords used where exact sequence matters
     SPECIALIST / DEPT-EXTRACTION: null role.include used correctly → score 3
  2  Mostly good; one item is 3 words at most, no full title phrases
  1  Multi-word title phrases present: ["Plant Manager", "VP Operations"]
  0  All items are full job title phrases

DIM 2 — Filter assignment  (0–4)
  4  Pattern correctly identified; domain/segment in keywords; stems in role.include;
     company.include only for hard target list (≤ ~15 named firms);
     category signals correctly converted to domain keywords; no title words in keywords
  3  One minor issue: title word in keywords alongside domain, OR ≤ 2 category companies
     in company.include
  2  Two minor issues, or one moderate misassignment
  1  Title/function words primarily in keywords; role.include empty (non-specialist);
     OR company.include contains obvious category-example companies
  0  Everything in keywords, role.include empty (non-specialist/non-dept); OR
     company.include used as a domain proxy with many category examples

DIM 3 — Archetype coverage  (0–2)
  Do queries collectively cover distinct candidate archetypes / access paths?
  2  2+ queries clearly target meaningfully different candidate populations — e.g. one
     via role.include stems + city location, one via keywords/domain + national sweep;
     collectively reaching candidates that any single query would miss.
     Specialist: widening keyword stems + location expansion across queries counts.
  1  Multiple queries with some differentiation but largely redundant — variations
     on the same strategy rather than genuinely different access paths.
  0  Single query only, OR all queries use the same signal combination reaching
     an identical candidate pool.

DIM 4 — Signal completeness  (0–1)
  1  Core requirement signals in role.include and/or keywords
  0  Key signals absent; both null/empty

DIM 5 — Location quality  (0–2)
  2  Plain text strings used (not numeric IDs).
     Tier 1 city: city-level text with appropriate scope.
     Tier 2/3: city + adjacent states or "India" — not city-only.
  1  Location present but one issue: e.g. only one query has location when multiple
     should vary geo coverage, or state-level used where city-level more appropriate.
  0  8-digit numeric Recruiter geo IDs used (wrong format).
     Tier 2/3 restricted to city-only (eliminates candidates).
     No location when requirement clearly specifies one.

DIM 6 — Stem discipline & anchoring  (0–2)
  Evaluates both failure directions: over-narrowing AND under-anchoring.
  This is the primary quality dimension for stem/keyword construction.
  2  Queries are well-balanced: role.include items are short stems (≤ 2 words each),
     AND a domain/sector anchor is present in keywords to direct them.
     No title words mixed into keywords alongside domain words. No AND logic.
     Each query opens a wide but directed door.
     AND used inside keywords string appropriately to focus a broad OR, when needed.
  1  One failure mode present but minor:
     • Mild over-specification: role.include has a 3-word phrase or one title-like item,
       OR keywords mixes one title word with domain words, but queries remain functional.
     • Mild under-anchoring: role.include present but keywords is null or very weak
       on one query, while other queries in the set have proper anchoring.
  0  A clear failure in either direction:
     OVER-NARROWING: role.include filled with full job title phrases; keywords mixes
       domain AND title words together; AND logic used excessively; multiple restrictive
       filters stacked simultaneously eliminating large candidate pools.
     UNDER-ANCHORING: generic role.include items (["operations","manufacturing","sales"])
       with keywords = null — no domain signal at all to direct the title stems;
       OR keywords is a sprawling OR-chain (5+ broad terms) with role.include = null
       and no AND sub-selection, retrieving profiles from every industry indiscriminately.`;
  }

  // classic
  return `${UNIVERSAL}
${CALIBRATION}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
SEARCH TYPE: LinkedIn Classic
Fields: keywords · advanced_keywords · location[] · company[] · past_company[]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

DIM 1 — Keyword quality  (0–3)
  Evaluates keywords boolean expression.
  3  Clean OR-expression of title/credential variations within the 6-term limit.
     Quoted phrases used for multi-word titles: "Chief Financial Officer", "plant head".
     Terms match the requirement's seniority band.
     SPECIALIST: credential stems, e.g. "pulmonologist" OR "chest physician".
  2  Good structure; ≤ 7 terms, or one minor domain word mixed in, or one
     unquoted multi-word phrase that should be quoted
  1  AND used (collapses recall); domain-only words with no title structure;
     comma-separated list without boolean operators; seniority band mismatch
  0  keywords null, 8+ terms, pure domain stuffing, or no title/credential structure

DIM 2 — Filter assignment  (0–4)
  4  Pattern correctly identified; keywords has title/credential OR-variations;
     company[] used only for hard target list (≤ ~15 named firms);
     category-signal companies correctly placed in past_company[] as background signal;
     domain correctly extracted to past_company[] context (not keywords); no domain words in keywords
  3  One minor issue: one domain word in keywords alongside titles, or small overlap
  2  Two minor issues, or one moderate error (e.g. company[] has ≤ 3 category examples)
  1  Domain words in keywords without title structure; OR company[] contains obvious
     category examples that should be in past_company[] or keywords
  0  keywords used for domain context only, no title structure; OR company[] used
     as a domain filter with many category-example companies

DIM 3 — Archetype coverage  (0–2)
  Do queries collectively cover distinct candidate archetypes / access paths?
  2  2+ queries clearly target meaningfully different candidate populations — e.g. one
     via tight title variants + city + company[], one via broader variants + national
     + past_company[] background signal, one via widest sweep with no location filter;
     collectively reaching candidates that any single query would miss.
     Specialist: widening keyword stems + location expansion across queries counts.
  1  Multiple queries with some differentiation but largely redundant — slightly
     different title variants but same overall strategy and candidate population.
  0  Single query only, OR all queries target the same narrow candidate pool.

DIM 4 — Signal completeness / term limit  (0–1)
  1  keywords ≤ 6 terms AND key signals from the requirement are captured
  0  More than 6 terms, OR key signals missing

DIM 5 — Location quality  (0–2)
  2  Plain text strings used (not numeric IDs).
     Tier 1 city: city-level string with appropriate scope.
     Tier 2/3: state + adjacent states as separate entries, or "India" in broader queries.
  1  Location present but one issue: e.g. only one query has location when multiple
     should vary geo coverage, or broader queries still city-restricted.
  0  Numeric geo IDs used (Recruiter format — wrong here).
     Tier 2/3 restricted to city-only (eliminates candidates).
     No location when requirement clearly specifies one.

DIM 6 — Stem discipline & anchoring  (0–2)
  Evaluates both failure directions: over-narrowing AND under-anchoring.
  This is the primary quality dimension for keyword/stem construction.
  NOTE for Classic: AND is NEVER correct inside keywords. Anchoring is done via past_company[].
  2  Queries are well-balanced: keywords contains only clean OR-connected title/credential
     variations (no domain words, no AND), stays within 6-term limit.
     Where title stems are generic (e.g. "plant head", "operations"), past_company[] provides
     a sector anchor that directs the OR-chain to the right candidate pool.
     Each query opens a wide but directed door.
  1  One failure mode present but minor:
     • Mild over-specification: one domain word leaked into keywords, or 7 terms used.
     • Mild under-anchoring: keywords has generic title variants but past_company[] is
       absent or thin on queries where a sector anchor would meaningfully focus results.
  0  A clear failure in either direction:
     OVER-NARROWING: AND used inside keywords (destroys recall), domain words mixed with
       title words, 8+ terms, or company[] used as domain proxy.
     UNDER-ANCHORING: generic title OR-chain (e.g. "manager" OR "head" OR "director")
       with no past_company[] or company[] anchor at all — surfaces every seniority
       role across all industries; OR keywords contains only domain words with no
       title/credential structure (pure domain stuffing).`;
}
